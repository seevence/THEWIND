CREATE TABLE career_jobs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source_key text NOT NULL,
  job_key text NOT NULL,
  company_name text NOT NULL,
  title text NOT NULL,
  official_url text NOT NULL,
  role_family text NOT NULL,
  degree text NOT NULL,
  employment_type text NOT NULL,
  student_friendly text NOT NULL,
  collector_version text NOT NULL,
  content_hash text NOT NULL,
  raw_text text NOT NULL,
  degree_raw text NULL,
  experience_raw text NULL,
  published_at text NULL,
  experience_min_years integer NULL,
  experience_max_years integer NULL,
  locations jsonb NULL,
  skills jsonb NULL,
  skill_evidence jsonb NULL,
  raw_payload jsonb NULL,
  fetched_at timestamptz NOT NULL,
  first_seen_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  UNIQUE (source_key, job_key)
);